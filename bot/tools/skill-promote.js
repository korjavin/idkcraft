'use strict'

// Skill promotion (idkcraft-vf8e.4): a green rig skill -> a generated PR,
// gated like a hand movement PR. Prod never runs a skill only a rig loop saw.
//
//   node tools/skill-promote.js <bead> <work-dir>/skills/<name>.js...
//   node tools/skill-promote.js demote <prod-log.txt...> [days=3]  (vf8e.22:
//     a skill banned on prod `days` days in a row loses its bot/skills file)
//
// Per skill, <work-dir>/result.json (skill-loop.js; SKILL_LOOP_VERIFY=<file>
// re-verifies a written skill without a model call) must be green for that
// skill. Then:
//   1. copy it to bot/skills/<name>.js with the header verifiedBy
//      {scenario, verdict, sha, body} and bead filled in;
//   2. gates with the copies loaded from bot/skills (BOT_SKILLS=1, no
//      SKILLS_DIR): the full stuck-run (body = the caller's REPLAY_BODY;
//      exit != 0 stops here, no PR) and the v2 component gates
//      CASTLE_BODY=baritone CASTLE_COMPONENT=lay|mine castle-rig.sh
//      (quoted, judged by review);
//   3. branch idkcraft-<bead>-skill-<names>, commit bot/skills, push, and a
//      draft PR labelled generated-skill whose body carries all three.
// Rig locks: RIG_LOCK_WAIT / CASTLE_LOCK_WAIT pass through (default 7200).
// Exit 0 = PR opened, 1 = refused (not green, a gate failed), 2 = usage/env.
// ponytail: one shot, no resume; a failed run leaves the copies in
// bot/skills for a look (git checkout -- bot/skills / rm to undo).

const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const { spawnSync } = require('node:child_process')
const { parseHeader } = require('../src/skills')

const BOT = path.join(__dirname, '..')
const HEADER_RE = /^\s*\/\*\s*skill\s*(\{[\s\S]*?\})\s*\*\//

// Absolute local paths never reach a PR body: keep the basename.
function scrub(s) {
  return String(s).replace(/(?:\/[\w.@-]+){2,}\/([\w.@-]+)/g, '$1')
}

// The green row's verdict, or a refusal string.
function greenVerdict(result, name, body = 'mineflayer') {
  if (!result || result.skill !== name) return `result.json is for ${result && result.skill}, not ${name}`
  if (!result.green || result.envFail) return `not green (${result.envFail || 'red'})`
  // Provenance must be real: a committed tree, the body the gates run on.
  if (!result.sha || result.sha === '?' || /-dirty$/.test(result.sha)) return `sha ${result.sha || 'missing'}: re-verify on a committed tree (SKILL_LOOP_VERIFY)`
  if (result.body !== body) return `verified on body ${result.body || 'unknown'}, gates run on ${body} (REPLAY_BODY)`
  const row = (result.rows || []).filter((r) => r.rc === 0).pop()
  if (!row) return 'no green row'
  return { verdict: scrub(row.verdict), attempt: row.attempt }
}

// A green run the skill never finished proves nothing (v2 may not wedge
// where v1 did): the attempt's bot log must show it done.
function ranDone(log, name) {
  return new RegExp(`^skill run skill=${name} kind=\\S+ outcome=done `, 'm').test(String(log))
}

// Header with verifiedBy + bead; the body below it is untouched.
function promoteText(text, result, verdict, bead) {
  const meta = parseHeader(text)
  meta.verifiedBy = { scenario: result.scenario, verdict, sha: result.sha, body: result.body }
  meta.bead = bead
  return text.replace(HEADER_RE, `/* skill ${JSON.stringify(meta)} */`)
}

// Stuck-run lines worth quoting: the table rows and the verdict lines.
function stuckLines(out) {
  return String(out).split('\n').filter((l) =>
    /^\S+\s+(?:true|false)\s+\d+\s+\d+\s+(?:true|false)\s/.test(l) || /^(?:BASELINE |baseline: |RERUN|FLAKY |verdict: )/.test(l)).map(scrub)
}

function componentLine(out, kind) {
  const l = String(out).split('\n').filter((x) => x.includes(`${kind}-rate `)).pop()
  return l ? scrub(l.trim()) : `(no ${kind}-rate line)`
}

// Mean rate of a component's legs vs the v2 baseline (CLAUDE.md v2 merge
// gate: more than 15% down = regression).
function meanLine(comps, kind, base) {
  const rates = comps.filter((c) => c.kind === kind).map((c) => /^\S+-rate ([\d.]+)\//.exec(c.line)).filter(Boolean).map((m) => Number(m[1]))
  if (!rates.length) return `${kind} mean: no rate`
  const mean = rates.reduce((a, b) => a + b, 0) / rates.length
  const pct = base > 0 ? Math.round((mean / base - 1) * 100) : null
  return `${kind} mean ${mean.toFixed(1)} over ${rates.length} legs (${rates.join(', ')})` +
    (pct == null ? '' : `, baseline ${base} (${pct >= 0 ? '+' : ''}${pct}%, ${pct >= -15 ? 'within' : 'REGRESSION'})`)
}

function prBody({ bead, skills, stuck, comps, commits }) {
  const s = []
  s.push(`Generated by \`bot/tools/skill-promote.js\` for bd ${bead}. Prod loads these only with \`BOT_SKILLS=1\` (v2: \`BOT2_SKILLS=1\`); rollback = flag off.`, '')
  s.push('### Skills (micro-rig verdict)')
  for (const k of skills) {
    s.push(`- \`${k.meta.name}\` (${k.meta.kind}, body ${k.meta.body}): ${k.meta.description}`)
    s.push(`  - scenario \`${k.result.scenario}\` (spot ${k.result.spot}, sabotage \`${k.result.sabotage}\`), rig body ${k.verifiedBy.body}, sha ${k.verifiedBy.sha}: \`${k.verifiedBy.verdict}\``)
  }
  s.push('', `### Full stuck-run (BOT_SKILLS=1, body ${stuck.body}): exit ${stuck.rc}`, '```', ...stuck.lines, '```')
  s.push('', '### Component gates (BOT_SKILLS=1, CASTLE_BODY=baritone, 10 game-min, vs component-baseline.json)')
  for (const c of comps) s.push(`- \`${c.cmd}\`: exit ${c.rc}: \`${c.line}\``)
  const base = JSON.parse(fs.readFileSync(path.join(__dirname, 'component-baseline.json'), 'utf8')).v2
  for (const kind of ['lay', 'mine']) s.push(`- **${meanLine(comps, kind, base[kind] && base[kind].rate)}**`)
  if (commits.length) s.push('', '### Commits', ...commits.map((c) => `- ${c}`))
  return s.join('\n') + '\n'
}

// --- Log-driven demotion (idkcraft-vf8e.22) ---
//
// A skill banned on prod 3 days in a row is demoted: the prod read (the same
// pulled bot2 log prod-score.js scores, `skill <name> banned ...` lines, one
// per UTC day) is the demotion input — log-driven, no rig.
//
//   node tools/skill-promote.js demote <log.txt...> [days=3]
//
// Deletes bot/skills/<name>.js for every demotable skill present there and
// prints `demote <name> banned=<days>` lines; skills banned fewer days print
// as `keep`. Exit 0 (nothing to demote is also 0), 2 on usage.

// Banned UTC days per skill from a pulled prod log (prod-score input shape:
// "YYYY-MM-DD HH:MM:SS <msg>"). The name rule is the skill header's, so chat
// `skills ...` lines and foreign paths never match.
function prodBans(text) {
  const bans = {}
  for (const line of String(text).split('\n')) {
    const m = /^(\d{4}-\d\d-\d\d) \d\d:\d\d:\d\d \S+ skill ([a-z][a-z0-9_]{1,39}) banned /.exec(line)
    if (!m) continue
    ;(bans[m[2]] || (bans[m[2]] = new Set())).add(m[1])
  }
  return Object.fromEntries(Object.entries(bans).map(([k, v]) => [k, [...v].sort()]))
}

const isoDay = (ms) => new Date(ms).toISOString().slice(0, 10)

// Skills banned on each of the `days` UTC days ending at the newest banned
// day in the input (a nightly job's trailing window: a recovered skill — no
// ban on the newest day — is kept, never demoted for an old run).
function demotable(bans, days = 3) {
  const all = Object.values(bans).flat()
  if (!all.length) return []
  const newest = all.sort().at(-1)
  const end = Date.parse(`${newest}T00:00:00Z`)
  const want = []
  for (let i = days - 1; i >= 0; i--) want.push(isoDay(end - i * 86400e3))
  return Object.entries(bans)
    .filter(([, ds]) => want.every((d) => ds.includes(d)))
    .map(([skill]) => ({ skill, days: want }))
}

// Delete the demotable skills' files from skillsDir. Returns {demoted, kept,
// missing}: demoted names the removed files, kept names banned-but-short
// skills, missing demotable skills with no file (already gone).
function demoteFromLog(text, skillsDir, days = 3) {
  const bans = prodBans(text)
  const table = demotable(bans, days)
  const demoted = []
  const missing = []
  for (const { skill, days: ds } of table) {
    const file = path.join(skillsDir, `${skill}.js`)
    if (fs.existsSync(file)) { fs.rmSync(file); demoted.push({ skill, days: ds }) }
    else missing.push({ skill, days: ds })
  }
  const hit = new Set(table.map((t) => t.skill))
  const kept = Object.entries(bans).filter(([s]) => !hit.has(s)).map(([skill, ds]) => ({ skill, days: ds }))
  return { demoted, kept, missing }
}

function demoteMain(files) {
  let days = 3
  if (files.length > 1 && /^\d+$/.test(files[files.length - 1])) days = Number(files.pop())
  if (!files.length || !(days >= 2)) {
    console.log('usage: node tools/skill-promote.js demote <log.txt...> [days=3]')
    return 2
  }
  const text = files.map((f) => fs.readFileSync(f, 'utf8')).join('\n')
  const { demoted, kept, missing } = demoteFromLog(text, path.join(BOT, 'skills'), days)
  for (const k of kept) console.log(`keep ${k.skill} banned-days=${k.days.length} last=${k.days.at(-1)}`)
  for (const m of missing) console.log(`missing ${m.skill} banned=${m.days.join(',')} (no bot/skills file)`)
  for (const d of demoted) console.log(`demote ${d.skill} banned=${d.days.join(',')}`)
  console.log(`skill-promote demote: demoted=${demoted.length} kept=${kept.length} missing=${missing.length} days=${days}`)
  return 0
}

function sh(cmd, args, env) {
  console.log(`skill-promote: ${cmd} ${args.join(' ')}`)
  const r = spawnSync(cmd, args, { cwd: BOT, env, encoding: 'utf8', maxBuffer: 512 * 1024 * 1024, stdio: ['ignore', 'pipe', 'pipe'] })
  const out = `${r.stdout || ''}${r.stderr || ''}`
  return { rc: r.status, out }
}

function main() {
  const [bead, ...files] = process.argv.slice(2)
  if (bead === 'demote') return demoteMain(files)
  if (!bead || !/^idkcraft-[\w.]+$/.test(bead) || !files.length) {
    console.log('usage: node tools/skill-promote.js <bead> <work-dir>/skills/<name>.js...')
    console.log('   or: node tools/skill-promote.js demote <log.txt...> [days=3]')
    return 2
  }
  const skills = []
  for (const f of files) {
    const text = fs.readFileSync(f, 'utf8')
    const meta = parseHeader(text)
    const work = path.join(path.dirname(f), '..')
    const result = JSON.parse(fs.readFileSync(path.join(work, 'result.json'), 'utf8'))
    const g = greenVerdict(result, meta.name, process.env.REPLAY_BODY || 'mineflayer')
    if (typeof g === 'string') { console.log(`skill-promote: ${meta.name}: ${g} — refused`); return 1 }
    let log = ''
    try { log = fs.readFileSync(path.join(work, `attempt-${g.attempt}.log`), 'utf8') } catch (_) { log = '' }
    if (!ranDone(log, meta.name)) { console.log(`skill-promote: ${meta.name}: the green run never finished the skill (no 'skill run ... outcome=done' in attempt-${g.attempt}.log) — refused`); return 1 }
    const out = promoteText(text, result, g.verdict, bead)
    skills.push({ meta: parseHeader(out), result, verifiedBy: parseHeader(out).verifiedBy, out })
  }
  for (const k of skills) fs.writeFileSync(path.join(BOT, 'skills', `${k.meta.name}.js`), k.out)

  const env = { ...process.env, BOT_SKILLS: '1', RIG_LOCK_WAIT: process.env.RIG_LOCK_WAIT || '7200', CASTLE_LOCK_WAIT: process.env.CASTLE_LOCK_WAIT || '7200' }
  delete env.SKILLS_DIR
  delete env.REPLAY_SKILLS_DIR
  delete env.REPLAY_KEEP
  const st = sh('sh', ['tools/stuck-run.sh'], env)
  const stuck = { rc: st.rc, body: process.env.REPLAY_BODY || 'mineflayer', lines: stuckLines(st.out) }
  // The raw gate output stays on disk: the quoted lines are a filter.
  const rawLog = path.join(fs.mkdtempSync(path.join(os.tmpdir(), 'skill-promote-stuck-')), 'stuck-run.log')
  fs.writeFileSync(rawLog, st.out)
  console.log(`${stuck.lines.join('\n')}\nskill-promote: full stuck-run output ${rawLog}`)
  if (st.rc !== 0) { console.log(`skill-promote: stuck-run exit ${st.rc} — refused (copies left in bot/skills)`); return 1 }
  // The baseline's settings (component-baseline.json setup); mine is judged
  // on the mean of 3 legs (one leg's within/OUTSIDE is noise).
  const padspot = process.env.CASTLE_PADSPOT || '250,350'
  const comps = []
  for (const [kind, legs] of [['lay', 1], ['mine', 3]]) {
    for (let i = 0; i < legs; i++) {
      const r = sh('sh', ['tools/castle-rig.sh'], { ...env, CASTLE_BODY: 'baritone', CASTLE_COMPONENT: kind, CASTLE_PADSPOT: padspot, CASTLE_RIG_ID: process.env.CASTLE_RIG_ID || 'auto' })
      comps.push({ kind, cmd: `CASTLE_BODY=baritone CASTLE_PADSPOT=${padspot} CASTLE_COMPONENT=${kind} sh bot/tools/castle-rig.sh`, rc: r.rc, line: componentLine(r.out, kind) })
      console.log(comps[comps.length - 1].line)
      if (r.rc === 2) { console.log(`skill-promote: castle-rig ${kind} environment failure — refused`); return 1 }
    }
  }

  const names = skills.map((k) => k.meta.name)
  const branch = `${bead}-skill-${names.join('-')}`
  const git = (...a) => {
    const r = sh('git', a, process.env)
    if (r.rc !== 0) throw new Error(`git ${a.join(' ')}: ${r.out.trim().slice(0, 300)}`)
    return r.out
  }
  git('checkout', '-b', branch)
  git('add', ...names.map((n) => `skills/${n}.js`))
  git('commit', '-m', `${bead}: promote skill ${names.join(', ')} (generated by skill-promote.js)`)
  git('push', '-u', 'origin', branch)
  const commits = git('log', '--format=%h %s', 'origin/master..HEAD').trim().split('\n').filter(Boolean)
  const bodyFile = path.join(fs.mkdtempSync(path.join(os.tmpdir(), 'skill-promote-')), 'body.md')
  fs.writeFileSync(bodyFile, prBody({ bead, skills, stuck, comps, commits }))
  sh('gh', ['label', 'create', 'generated-skill', '--force', '--color', '5319e7', '--description', 'PR opened by bot/tools/skill-promote.js'], process.env)
  const pr = sh('gh', ['pr', 'create', '--draft', '--head', branch, '--label', 'generated-skill', '--title', `${bead}: promote skill ${names.join(', ')}`, '--body-file', bodyFile], process.env)
  console.log(pr.out.trim())
  return pr.rc === 0 ? 0 : 2
}

if (require.main === module) {
  let rc = 2
  try { rc = main() } catch (e) { console.log(e && e.stack ? e.stack : e) }
  process.exit(rc)
}

module.exports = { scrub, greenVerdict, ranDone, promoteText, stuckLines, componentLine, meanLine, prBody, prodBans, demotable, demoteFromLog, demoteMain }
